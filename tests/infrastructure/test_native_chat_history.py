from behave.train.training_data import NativeChatVerifier, TokenTrace, TrainingRequirements


def capture(endpoint, packet):
    req, raw = request(endpoint), canonical_json(packet)
    reply = attach_tokens(endpoint.tokens, req, response(endpoint, 200, raw))
    return TokenTrace.from_dict(thaw_json(reply.token_data)), req, raw


def requirements(endpoint):
    return TrainingRequirements(endpoint.tokens.adapter, endpoint.tokens.checkpoint,
                                endpoint.tokens.tokenizer, endpoint.tokens.template)


@pytest.mark.parametrize("runtime", ["sglang", "vllm"])
def test_explicit_history_verifies_two_policies_and_multiple_server_incarnations(runtime):
    first, packet = native(runtime)
    second = replace(first, runtime_revision="after-update",
                     tokens=replace(first.tokens, checkpoint=BlobRef.of(b"new-weights")))
    restarted = replace(second, url="http://127.0.0.1:49123/v1/chat/completions")
    if restarted.identity == second.identity:
        restarted = replace(second, url="http://127.0.0.1:49124/v1/chat/completions")
    verifier = NativeChatVerifier(first, second, restarted)
    assert verifier.identity == first.tokens.adapter
    for endpoint in (first, second, restarted):
        verifier.require(requirements(endpoint))
        verifier.verify(*capture(endpoint, packet))
    # An incomplete operator history cannot silently treat past samples as
    # generated by the currently loaded weights.
    with pytest.raises(ValueError, match="policy differs"):
        NativeChatVerifier(second).verify(*capture(first, packet))
    with pytest.raises(ValueError, match="policy differs"):
        NativeChatVerifier(first).verify(*capture(second, packet))
    unknown = replace(second, runtime_revision="unapproved-incarnation")
    with pytest.raises(ValueError, match="policy differs"):
        verifier.verify(*capture(unknown, packet))
    with pytest.raises(RecordError, match="no approved endpoint"):
        verifier.require(replace(requirements(first), checkpoint=BlobRef.of(b"unknown-weights")))
    trace, req, raw = capture(first, packet)
    with pytest.raises(RecordError, match="trace differs"):
        verifier.verify(replace(trace, checkpoint=second.tokens.checkpoint), req, raw)


def test_endpoint_history_is_explicit_and_same_dialect(tmp_path):
    first, _ = native("sglang")
    second = replace(first, runtime_revision="second")
    paths = [tmp_path / f"endpoint-{index}.json" for index in range(2)]
    for path, endpoint in zip(paths, (first, second), strict=True):
        path.write_bytes(canonical_json(endpoint.as_dict()))
    verifier = NativeChatVerifier.from_files(paths)
    assert tuple(verifier.endpoints) == (first.identity, second.identity)
    assert tuple(NativeChatVerifier.from_file(paths[0]).endpoints) == (first.identity,)
    # Duplicate approved files are idempotent, not an ambiguous selection rule.
    assert len(NativeChatVerifier.from_files([paths[0], paths[0]]).endpoints) == 1
    with pytest.raises(TypeError):
        verifier.endpoints[first.identity] = second
    with pytest.raises(ValueError, match="at least one"):
        NativeChatVerifier.from_files([])
    other, _ = native("vllm")
    with pytest.raises(ValueError, match="one native token adapter"):
        NativeChatVerifier(first, other)
    with pytest.raises(ValueError, match="token-enabled"):
        NativeChatVerifier(first, replace(second, tokens=None))
    paths[1].write_bytes(b"not JSON")
    with pytest.raises(ValueError):
        NativeChatVerifier.from_files(paths)


def test_native_verifier_loads_the_same_large_valid_endpoint_as_the_broker(tmp_path):
    first, packet = native("sglang")
    endpoint = replace(first, parameters={**first.parameters, "chat_template_kwargs": {"fixture": "x" * (33 << 10)}})
    path = tmp_path / "endpoint.json"
    path.write_bytes(canonical_json(endpoint.as_dict()))
    verifier = NativeChatVerifier.from_file(path)
    verifier.verify(*capture(endpoint, packet))
    assert tuple(verifier.endpoints) == (endpoint.identity,)


@pytest.mark.isolation
def test_two_policy_reports_survive_checkpoint_cold_restore_without_a_live_server(tmp_path, publication, monkeypatch):
    from test_infra_cli import command
    from test_training_checkpoints import state_at

    from behave.agent.journal import load_chain
    from behave.agent.run_store import JournalDirectory
    from behave.core.storage import DirectoryStore
    from behave.train.checkpoints import TrainingLedger, load_checkpoint, restore_ledger
    from behave.train.learning_report import load_training_report
    from behave.train.update_records import ExampleUse, TrainerContract, UpdateRequest

    # Two supervised HTTP rollouts use different fixture policy identities.
    # The responses and opaque state are fixtures, not numerical updates.
    rounds = [native_training_run(tmp_path / str(index), publication,
                                  checkpoint=BlobRef.of(f"weights-{index}".encode())) for index in range(2)]
    endpoints = [row[4] for row in rounds]
    verifier = NativeChatVerifier(*endpoints)
    source = DirectoryStore(tmp_path / "source")
    reports = []
    for rollout, manifest, _, summary, _ in rounds:
        head, closure = rollout.seal("training")
        source.publish(rollout.objects, closure)
        reports.append((head, summary))
    assert rounds[0][1] == rounds[1][1]
    contract = TrainerContract("history-fixture/1", source.put(b"not-an-optimizer"), manifest)
    run = JournalDirectory(tmp_path / "trainer")
    with TrainingLedger(run, contract, verifier=verifier) as ledger:
        current = ledger.initialize(replace(state_at(source), policy=endpoints[0].tokens.checkpoint), source)
        for index, (head, _) in enumerate(reports):
            pending = ledger.begin(UpdateRequest(
                f"update-{index}", current.reference,
                tuple(ExampleUse(head, 0, turn, "epoch-0") for turn in (0, 2)),
                source.put(b"explicit-use-decision"),
            ), source)
            assert all(row["tokens"]["checkpoint"] == endpoints[index].tokens.checkpoint.as_dict()
                       for row in pending.examples)
            current = ledger.commit(pending.reference, replace(
                state_at(source, index + 1), policy=BlobRef.of(f"weights-{index + 1}".encode())), source)
        head, closure = ledger.seal()
    cold = DirectoryStore(tmp_path / "cold")
    cold.publish(run.objects, closure)
    from behave.isolation import service

    monkeypatch.setattr(service, "run_service", lambda *a, **kw: pytest.fail("offline verification dispatched"))
    assert load_checkpoint(cold, head, contract=contract, verifier=verifier) == (current, None)
    assert restore_ledger(cold, head, run=JournalDirectory(tmp_path / "restored"),
                          contract=contract, verifier=verifier) == (current, None)
    with pytest.raises(ValueError, match="policy differs"):
        load_checkpoint(cold, head, contract=contract, verifier=NativeChatVerifier(endpoints[-1]))
    for ref, expected in reports:
        assert load_training_report(cold, ref, approved_manifest=manifest, verifier=verifier) == expected
        # A length-finished middle turn keeps its sampled tokens eligible.
        assert [turn["status"] for turn in expected["candidates"][0]["examples"]["turns"]] == [
            "eligible", "eligible", "eligible"]
    # The public CLI receives the approved history separately, not from
    # fields in the report. Existing single-file invocations remain valid.
    manifest_path, head_path = tmp_path / "manifest.json", tmp_path / "head.json"
    manifest_path.write_bytes(source.read(manifest))
    history_args = []
    for index, endpoint in enumerate(endpoints):
        path = tmp_path / f"endpoint-{index}.json"
        path.write_bytes(canonical_json(endpoint.as_dict()))
        history_args.extend(("--native-endpoint", path))
    for ref, expected in reports:
        head_path.write_bytes(canonical_json(ref.as_dict()))
        result = command("inspect", "--kind", "train", "--objects", cold.directory,
                         "--record", head_path, "--approved-manifest", manifest_path, *history_args)
        assert result.returncode == 0, result.stderr + result.stdout
        assert parse_json(result.stdout) == expected
        plan_ref = BlobRef.from_dict(thaw_json(load_chain(cold, ref)[0].payload["plan"]))
        plan_path = tmp_path / "plan.json"
        plan_path.write_bytes(cold.read(plan_ref))
        preflight = command("train", "--plan", plan_path, "--task-objects", cold.directory,
                            "--approved-manifest", manifest_path, "--dry-run", *history_args)
        assert preflight.returncode == 0, preflight.stderr + preflight.stdout
        assert parse_json(preflight.stdout)["status"] == "validated"

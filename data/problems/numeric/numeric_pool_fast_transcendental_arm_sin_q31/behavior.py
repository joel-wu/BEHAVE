def sine_sample(index):
    index &= 511
    if index <= 128:
        return QUARTER[index]
    if index <= 256:
        return QUARTER[256 - index]
    if index == 384:
        return -2147483648
    if index < 384:
        return -QUARTER[index - 256]
    return -QUARTER[512 - index]


class FastQ31Sine:
    def __init__(self):
        self.reset()

    def reset(self):
        pass

    def process(self, in_x):
        phase = (in_x + 0) & 0x7FFFFFFF
        index = phase >> 22
        fraction = (phase & 0x003FFFFF) << 9
        a = sine_sample(index)
        b = sine_sample(index + 1)
        first = ((0x80000000 - fraction) * a) >> 32
        second = (fraction * b) >> 32
        return {"out_sin": ((first + second) << 1) & 0xFFFFFFFF}

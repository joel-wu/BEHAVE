class SinCosDegreesF32:
    def __init__(self):
        self.reset()

    def reset(self):
        pass

    def _trunc_to_u32(self, x):
        expv = (x >> 23) & 0xFF
        fracv = x & 0x7FFFFF
        if expv == 0:
            return 0
        e = expv - 127
        if e < 0:
            return 0
        mant = (1 << 23) | fracv
        if e >= 23:
            return to_unsigned(mant << (e - 23), 32)
        return mant >> (23 - e)

    def _u32_to_fp32(self, x):
        x = to_unsigned(x, 32)
        if x == 0:
            return 0
        msb = 31
        for i in range(31, -1, -1):
            if (x >> i) & 1:
                msb = i
                break
        expv = msb + 127
        if msb <= 23:
            shifted = to_unsigned(x << (23 - msb), 32)
            return (expv << 23) | (shifted & 0x7FFFFF)
        shifted = x >> (msb - 23)
        return (expv << 23) | (shifted & 0x7FFFFF)

    def process(self, in_theta):
        theta = to_unsigned(in_theta, 32)
        if fp32_is_nan(theta) or fp32_is_inf(theta):
            return {"out_sin": CANON_NAN, "out_cos": CANON_NAN}

        in_v = fp32_mul(theta, INV_360)
        if fp32_cmp(in_v, ZERO) < 0:
            in_v = fp32_neg(in_v)

        # Binary32 magnitudes >= 2**23 already have no fractional bits.
        # Below this threshold the integer conversion is exact and bounded.
        if (in_v & 0x7FFFFFFF) >= 0x4B000000:
            in_v = ZERO
        else:
            int_part = self._trunc_to_u32(in_v)
            in_v = fp32_sub(in_v, self._u32_to_fp32(int_part))

        findex = fp32_mul(TABLE_SIZE_FP32, in_v)
        indexS = self._trunc_to_u32(findex) & 0x1FF
        indexC = (indexS + 128) & 0x1FF
        fract = fp32_sub(findex, self._u32_to_fp32(indexS))

        f1 = SIN_TABLE_F32[indexC]
        f2 = SIN_TABLE_F32[indexC + 1]
        d1 = fp32_neg(SIN_TABLE_F32[indexS])
        d2 = fp32_neg(SIN_TABLE_F32[indexS + 1])
        Df = fp32_sub(f2, f1)
        temp = fp32_sub(fp32_mul(DN, fp32_add(d1, d2)), fp32_mul(TWO, Df))
        temp = fp32_add(fp32_mul(fract, temp), fp32_sub(fp32_mul(THREE, Df), fp32_mul(fp32_add(d2, fp32_mul(TWO, d1)), DN)))
        temp = fp32_add(fp32_mul(fract, temp), fp32_mul(d1, DN))
        cos_val = fp32_add(fp32_mul(fract, temp), f1)

        f1 = SIN_TABLE_F32[indexS]
        f2 = SIN_TABLE_F32[indexS + 1]
        d1 = SIN_TABLE_F32[indexC]
        d2 = SIN_TABLE_F32[indexC + 1]
        Df = fp32_sub(f2, f1)
        temp = fp32_sub(fp32_mul(DN, fp32_add(d1, d2)), fp32_mul(TWO, Df))
        temp = fp32_add(fp32_mul(fract, temp), fp32_sub(fp32_mul(THREE, Df), fp32_mul(fp32_add(d2, fp32_mul(TWO, d1)), DN)))
        temp = fp32_add(fp32_mul(fract, temp), fp32_mul(d1, DN))
        sin_val = fp32_add(fp32_mul(fract, temp), f1)

        if fp32_cmp(theta, ZERO) < 0:
            sin_val = fp32_neg(sin_val)

        return {"out_sin": to_unsigned(sin_val, 32), "out_cos": to_unsigned(cos_val, 32)}

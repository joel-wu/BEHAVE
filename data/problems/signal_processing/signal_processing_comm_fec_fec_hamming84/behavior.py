def to_unsigned(v, b):
    return v & ((1 << b) - 1)


class SignalProcessingCommFecFecHamming84:
    def __init__(self):
        self.reset()

    def reset(self):
        pass

    def process(self, in_encode, in_data0, in_data1):
        if in_encode & 1:
            s0 = (in_data0 >> 4) & 0x0F
            s1 = in_data0 & 0x0F
            return [
                {"out_data": to_unsigned(ENC_TABLE[s0], 8)},
                {"out_data": to_unsigned(ENC_TABLE[s1], 8)},
            ]
        r0 = in_data0 & 0xFF
        r1 = in_data1 & 0xFF
        s0 = DEC_TABLE[r0]
        s1 = DEC_TABLE[r1]
        return {"out_data": to_unsigned((s0 << 4) | s1, 8)}
def to_unsigned(v, b):
    return v & ((1 << b) - 1)


class Hamming74Codec:
    def __init__(self):
        self.reset()

    def reset(self):
        pass

    def _soft_decode_symbol(self, soft):
        s_hat = 0
        dmin = 0
        for s in range(16):
            c = ENC_TABLE[s]
            d = 0
            d += (255 - soft[0]) if (c & 0x40) else soft[0]
            d += (255 - soft[1]) if (c & 0x20) else soft[1]
            d += (255 - soft[2]) if (c & 0x10) else soft[2]
            d += (255 - soft[3]) if (c & 0x08) else soft[3]
            d += (255 - soft[4]) if (c & 0x04) else soft[4]
            d += (255 - soft[5]) if (c & 0x02) else soft[5]
            d += (255 - soft[6]) if (c & 0x01) else soft[6]
            if d < dmin or s == 0:
                s_hat = s
                dmin = d
        return s_hat

    def process(
        self,
        in_mode,
        in_data,
        in_code0,
        in_code1,
        in_soft0,
        in_soft1,
        in_soft2,
        in_soft3,
        in_soft4,
        in_soft5,
        in_soft6,
        in_soft7,
        in_soft8,
        in_soft9,
        in_soft10,
        in_soft11,
        in_soft12,
        in_soft13,
    ):
        mode = in_mode & 0x3

        if mode == 0x1:
            nibble0 = DEC_TABLE.get(in_code0 & 0x7F, 0)
            nibble1 = DEC_TABLE.get(in_code1 & 0x7F, 0)
            return {
                "out_data": to_unsigned((nibble0 << 4) | nibble1, 8),
                "out_code0": 0,
                "out_code1": 0,
            }

        if mode == 0x2:
            soft0 = [
                in_soft0 & 0xFF, in_soft1 & 0xFF, in_soft2 & 0xFF, in_soft3 & 0xFF,
                in_soft4 & 0xFF, in_soft5 & 0xFF, in_soft6 & 0xFF,
            ]
            soft1 = [
                in_soft7 & 0xFF, in_soft8 & 0xFF, in_soft9 & 0xFF, in_soft10 & 0xFF,
                in_soft11 & 0xFF, in_soft12 & 0xFF, in_soft13 & 0xFF,
            ]
            nibble0 = self._soft_decode_symbol(soft0)
            nibble1 = self._soft_decode_symbol(soft1)
            return {
                "out_data": to_unsigned((nibble0 << 4) | nibble1, 8),
                "out_code0": 0,
                "out_code1": 0,
            }

        nibble0 = (in_data >> 4) & 0xF
        nibble1 = in_data & 0xF
        return {
            "out_data": 0,
            "out_code0": to_unsigned(ENC_TABLE[nibble0], 7),
            "out_code1": to_unsigned(ENC_TABLE[nibble1], 7),
        }
class AiMlAudioMelMfccDct:
    def __init__(self):
        self.reset()

    def reset(self):
        self.zero = 0

    def process(self, in_n_mfcc, in_n_mels, in_k, in_norm_ortho):
        n_mfcc = to_unsigned(in_n_mfcc, 8)
        n_mels = to_unsigned(in_n_mels, 8)
        k = to_unsigned(in_k, 8)
        norm_ortho = to_unsigned(in_norm_ortho, 1)
        mels_legal = (n_mels == 1) or (n_mels == 2) or (n_mels == 4) or (n_mels == 8)
        out = {}
        for i in range(16):
            valid = mels_legal and (k < 8) and (i < n_mels) and (k < n_mfcc)
            if valid:
                key = ((norm_ortho << 21) | (n_mels << 13)
                       | (k << 5) | i)
                bits = _LUT.get(key, 0)
            else:
                bits = 0
            out[f"out_coeff_{i}"] = to_unsigned(bits, 32)
        return out

def signed(x,bits):
    return ((x+(1 << (bits-1))) & ((1 << bits)-1))-(1 << (bits-1))

def nearest(x,d):
    q=abs(x)//d
    r=abs(x)-q*d
    if 2*r>d or (2*r==d and (q & 1)!=0):
        q+=1
    if x<0:q=-q
    return q


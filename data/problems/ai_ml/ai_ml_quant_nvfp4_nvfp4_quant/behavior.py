def positive_normal(v):
    return v >> 31 == 0 and 0 < ((v >> 23) & 255) < 255


def scale_code(value):
    if value <= 0x3B000000:
        return 1
    code = 126
    found = False
    for k in range(1,126):
        if not found and (value < MID[k-1] or (value == MID[k-1] and (k & 1) == 0)):
            code = k
            found = True
    return code


def element_code(value):
    magnitude = value & 0x7FFFFFFF
    sign = 8 if value >> 31 and magnitude != 0 else 0
    code = 7
    found = False
    for k in range(7):
        if not found and (magnitude < BOUND[k] or (magnitude == BOUND[k] and (k & 1) == 0)):
            code = k
            found = True
    return sign | code



    function automatic logic signed [31:0] sat32(input logic signed [63:0] x);
        if(x>64'sd2147483647) sat32=32'sh7fffffff;
        else if(x < -64'sd2147483648) sat32=32'sh80000000;
        else sat32=x[31:0];
    endfunction

    function automatic logic signed [63:0] floor_div(
        input logic signed [63:0] a,input logic signed [63:0] b);
        floor_div=a>=0 ? a/b : -((-a+b-1)/b);
    endfunction


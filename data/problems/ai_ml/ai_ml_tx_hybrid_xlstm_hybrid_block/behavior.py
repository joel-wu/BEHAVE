def signed(word, width):
    value = word & ((1 << width)-1)
    return value-(1 << width) if value >= (1 << (width-1)) else value


def sat32(value):
    return max(-2147483648, min(2147483647, value))


def exp_word(index):
    return EXP[index+188] if index >= -188 else 0


class MLSTMRecurrentCore:
    def __init__(self):
        self.reset()

    def reset(self):
        pass

    def process(self, in_query, in_key, in_value, in_igate, in_fgate,
                in_state_valid, in_cstate, in_nstate, in_mstate):
        old_m = signed(in_mstate, 16) if in_state_valid else 0
        if old_m < -128 or old_m > 128:
            return {"out_h": 0, "out_cstate": 0, "out_nstate": 0,
                    "out_mstate": 0, "out_error": 1}
        i = signed(in_igate, 8)
        f_log = LOG_F[signed(in_fgate, 8)+128]
        m = max(old_m+f_log, i)
        forget = exp_word(old_m+f_log-m)
        insert = exp_word(i-m)
        c = [0] * 8
        n = [0] * 4
        packed_c = 0
        packed_n = 0
        for r in range(4):
            k = signed(in_key >> (16*r), 16)
            old_n = signed(in_nstate >> (32*r), 32) if in_state_valid else 0
            n[r] = sat32((forget*old_n + insert*k*256) // 65536)
            packed_n |= (n[r] & 4294967295) << (32*r)
            for j in range(2):
                v = signed(in_value >> (16*j), 16)
                old_c = signed(in_cstate >> (32*(2*r+j)), 32) if in_state_valid else 0
                c[2*r+j] = sat32((forget*old_c + insert*k*v) // 65536)
                packed_c |= (c[2*r+j] & 4294967295) << (32*(2*r+j))
        qn = 0
        for r in range(4):
            qn += signed(in_query >> (16*r), 16)*n[r]
        denominator = max(abs(qn // 512), exp_word(-m)) + 1
        packed_h = 0
        for j in range(2):
            numerator = 0
            for r in range(4):
                numerator += signed(in_query >> (16*r), 16)*c[2*r+j]
            h = max(-32768, min(32767, ((numerator // 512)*256) // denominator))
            packed_h |= (h & 65535) << (16*j)
        return {"out_h": packed_h, "out_cstate": packed_c, "out_nstate": packed_n,
                "out_mstate": m & 65535, "out_error": 0}

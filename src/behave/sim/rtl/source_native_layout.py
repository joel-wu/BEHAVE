"""Bind anonymous source scopes through the native compiler, without HDL edits.

The source frontend's logical block keys are not VPI names. Only a native
compiler scope at the same original source coordinate can supply such a name.
Ambiguous, missing and generated-only locations remain unavailable; neither
lexical name matching nor a default state value is a substitute.
"""

import json
from pathlib import Path
import sys

from .source_storage import anonymous_scope_name

_PREFIX = "__behave_native_event_block_"


def needs_layout(fields):
    return any(isinstance(name, tuple) and any(
        isinstance(part, str) and part.startswith(_PREFIX) for part in name)
        for name, _shape in fields)


def scope_paths(document, metadata, edits, fields, *, filename="native.sv"):
    files = {key for key, value in metadata["files"].items()
             if Path(value["filename"]).name == filename}
    names = {}

    pending = [(document, (), ())]
    while pending:
        node, logical, native = pending.pop()
        if isinstance(node, dict):
            if node.get("type") == "MODULE":
                logical, native = (), ()
            if node.get("type") == "BEGIN" and node.get("name"):
                native = (*native, node["name"])
                file, first, _last = node["loc"].split(",")
                if file in files:
                    line, column = map(int, first.split(":"))
                    try:
                        following = edits.source_position(line, column + 1)
                        line, column = edits.source_position(line, column)
                        if following != (line, column + 1):
                            raise ValueError("generated scope token")
                    except ValueError:
                        pass  # Observer-generated bytes do not declare source scopes.
                    else:
                        key = (anonymous_scope_name({"source_line": line, "source_column": column})
                               if node.get("unnamed") else node["name"])
                        logical = (*logical, key)
                        if node.get("unnamed"):
                            names.setdefault(key, set()).add((logical, native))
            for value in node.values():
                if isinstance(value, (dict, list)):
                    pending.append((value, logical, native))
        elif isinstance(node, list):
            pending.extend((value, logical, native) for value in node)

    paths = []
    for name, _shape in fields:
        if not isinstance(name, tuple) or not any(
                isinstance(part, str) and part.startswith(_PREFIX) for part in name):
            continue
        # Match the entire compiler scope, including observer-created parents.
        # Replacing individual block names drops these parents around loops.
        end = max(i for i, part in enumerate(name)
                  if isinstance(part, str) and part.startswith(_PREFIX)) + 1
        choices = set()
        for logical, native in names.get(name[end - 1], ()):
            start = end - len(logical)
            if start >= 0 and name[start:end] == logical:
                choices.add((*name[:start], *native, *name[end:]))
        paths.append((name, next(iter(choices)) if len(choices) == 1 else None))
    return tuple(paths)


def prepare_paths(root, top, edits, fields, *, run):
    """One optional compile-time witness; never another simulation or score."""
    from behave.core.runtime_defaults import SIM_EDA_NORMALIZATION_RECURSION_LIMIT
    from .native_events import VERILATOR_FLAGS

    if not needs_layout(fields):
        return ()
    # All logical fields are still recorded on failure, with unavailable values.
    # A query must then report the missing boundary instead of fabricating it.
    unavailable = tuple((name, None) for name, _shape in fields
                        if needs_layout(((name, _shape),)))
    if not run(root, "/tools/verilator", "--json-only", "--json-only-output", "layout.json",
               "--Mdir", "layout", "--prefix", "Vtop", "--top-module", top,
               "--timescale", "1ns/1ps", "--vpi", "--public-flat-rw", "-Wno-fatal",
               *VERILATOR_FLAGS, "native.sv"):
        return unavailable
    # Like the port-tree normalizer, this runs inside the disposable tool
    # process. Compiler expression depth is not Python call depth: use the
    # existing EDA decoding limit, then traverse the tree iteratively.
    previous_limit = sys.getrecursionlimit()
    try:
        sys.setrecursionlimit(max(previous_limit, SIM_EDA_NORMALIZATION_RECURSION_LIMIT))
        return scope_paths(json.loads((root / "layout.json").read_text()),
                           json.loads((root / "layout/Vtop.tree.meta.json").read_text()),
                           edits, fields)
    except (OSError, ValueError, KeyError, TypeError, RecursionError):
        # A failed optional compiler witness cannot invalidate native replay.
        return unavailable
    finally:
        sys.setrecursionlimit(previous_limit)

"""HDL edits with an exact inverse UTF-8 source map.

Generated bytes have no source meaning. An endpoint inside an insertion is
therefore an error, not a nearby original position. Endpoints at its boundaries
both map to the original insertion point. Storage is linear in the number of
edits and lines, not the number of source bytes times the number of edits.
Replaced tokens have the same rule: only their endpoints map to the original
range. Generated interiors never acquire an invented source coordinate.
"""

from bisect import bisect_right
from dataclasses import dataclass, field
import re


@dataclass(frozen=True, slots=True)
class Insertion:
    offset: int
    text: str


@dataclass(frozen=True, slots=True)
class Replacement:
    start: int
    end: int
    text: str


def relocate_expression(source: bytes, span, insertions, replacements=()):
    """Render a moved expression with all its existing probes and token edits.

    The caller replaces the original range once. Keeping relocation here makes
    continuous drivers and deferred selectors compose with the same transforms;
    neither is allowed to drop a nested operation or read probe.
    """
    first, last = span
    local, retained = [], []
    for edit in insertions:
        if first <= edit.offset <= last:
            local.append(Insertion(edit.offset - first, edit.text))
        else:
            retained.append(edit)
    moved, remaining = [], []
    for edit in replacements:
        if first <= edit.start and edit.end <= last:
            moved.append(Replacement(edit.start - first, edit.end - first, edit.text))
        elif edit.start < last and first < edit.end:
            raise ValueError("an expression relocation crosses a source replacement")
        else:
            remaining.append(edit)
    value = SourceEdits(source[first:last].decode("utf-8"),
                        tuple(sorted(local, key=lambda edit: edit.offset)),
                        tuple(sorted(moved, key=lambda edit: edit.start))).text
    return value, retained, remaining


def _lines(data: bytes) -> tuple[int, ...]:
    return (0, *(match.end() for match in re.finditer(b"\n", data)))


@dataclass(frozen=True, slots=True)
class SourceEdits:
    source: str
    insertions: tuple[Insertion, ...]
    replacements: tuple[Replacement, ...] = ()
    text: str = field(init=False)
    _original: bytes = field(init=False, repr=False)
    _generated: bytes = field(init=False, repr=False)
    _spans: tuple[tuple[int, int, int, int], ...] = field(init=False, repr=False)
    _ends: tuple[int, ...] = field(init=False, repr=False)
    _source_lines: tuple[int, ...] = field(init=False, repr=False)
    _generated_lines: tuple[int, ...] = field(init=False, repr=False)

    def __post_init__(self):
        if type(self.source) is not str or type(self.insertions) is not tuple \
                or type(self.replacements) is not tuple:
            raise TypeError("source edits need exact text and immutable edit tuples")
        original = self.source.encode("utf-8")
        changes, previous = [], 0
        for edit in self.insertions:
            if type(edit) is not Insertion or type(edit.offset) is not int \
                    or type(edit.text) is not str or not edit.text:
                raise TypeError("invalid source insertion")
            if not previous <= edit.offset <= len(original):
                raise ValueError("insertions must be ordered and within the source")
            changes.append((edit.offset, edit.offset, edit.text))
            previous = edit.offset
        previous = 0
        for edit in self.replacements:
            if type(edit) is not Replacement or type(edit.start) is not int \
                    or type(edit.end) is not int or type(edit.text) is not str or not edit.text:
                raise TypeError("invalid source replacement")
            if not previous <= edit.start < edit.end <= len(original):
                raise ValueError("replacements must be ordered, disjoint and within the source")
            changes.append((edit.start, edit.end, edit.text))
            previous = edit.end
        # Preserve insertion order at an equal offset. Insertions at a token's
        # beginning belong before its replacement; those at its end follow it.
        changes.sort(key=lambda row: row[:2])
        spans, pieces, cursor, size = [], [], 0, 0
        for start, end, text in changes:
            if start < cursor:
                raise ValueError("an insertion overlaps a source replacement")
            if any(point < len(original) and original[point] & 0xC0 == 0x80
                   for point in (start, end)):
                raise ValueError("a source edit splits a UTF-8 character")
            unchanged, added = original[cursor:start], text.encode("utf-8")
            pieces.extend((unchanged, added))
            size += len(unchanged)
            spans.append((size, size + len(added), start, end))
            size += len(added)
            cursor = end
        pieces.append(original[cursor:])
        generated = b"".join(pieces)
        for name, value in {
            "text": generated.decode("utf-8"), "_original": original,
            "_generated": generated, "_spans": tuple(spans),
            "_ends": tuple(span[1] for span in spans),
            "_source_lines": _lines(original), "_generated_lines": _lines(generated),
        }.items():
            object.__setattr__(self, name, value)

    def source_offset(self, offset: int) -> int:
        """Map a generated byte boundary back; never invent a generated location."""
        if type(offset) is not int or not 0 <= offset <= len(self._generated):
            raise ValueError("generated offset is outside the source map")
        index = bisect_right(self._ends, offset)
        if index < len(self._spans):
            start, end, _first, _last = self._spans[index]
            if start < offset < end:
                raise ValueError("a generated position has no original source coordinate")
        shift = 0 if index == 0 else self._spans[index - 1][1] - self._spans[index - 1][3]
        return offset - shift

    def source_position(self, line: int, column: int) -> tuple[int, int]:
        """Map one-based compiler line/byte-column coordinates."""
        if type(line) is not int or type(column) is not int or column < 1 \
                or not 1 <= line <= len(self._generated_lines):
            raise ValueError("invalid generated source coordinate")
        offset = self._generated_lines[line - 1] + column - 1
        end = (self._generated_lines[line] - 1 if line < len(self._generated_lines)
               else len(self._generated))
        if offset > end:
            raise ValueError("generated column is outside its line")
        return self.original_position(self.source_offset(offset))

    def original_position(self, offset: int) -> tuple[int, int]:
        if type(offset) is not int or not 0 <= offset <= len(self._original):
            raise ValueError("original offset is outside the source map")
        line = bisect_right(self._source_lines, offset)
        return line, offset - self._source_lines[line - 1] + 1
